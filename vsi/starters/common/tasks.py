"""One-word project commands (Windows, macOS, Linux).

    python tasks.py setup      install dependencies (VSI is the vsi/ folder)
    python tasks.py data       download official data (if the project has src/download.py)
    python tasks.py test       run tests (must stay green)
    python tasks.py run        run all algorithms on all instances -> results/metrics.csv
    python tasks.py plots      charts from results/ -> results/*.png
    python tasks.py check      requirements progress from docs/REQUIREMENTS.md
    python tasks.py context    write CONTEXT.md (one file to upload to ChatGPT / Copilot 365 / Gemini web)
"""

from __future__ import annotations

import os
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
sys.path[:0] = [str(ROOT / "src"), str(ROOT)]
os.chdir(ROOT)


def setup(_):
    subprocess.check_call([sys.executable, "-m", "pip", "install", "-r", "requirements.txt"])


def data(_):
    try:
        import download
    except ImportError:
        print("This project has no src/download.py (data is generated by src/generator.py).")
        return
    download.main()


def test(args):
    sys.exit(subprocess.call([sys.executable, "-m", "pytest", "-q", *args]))


def run(args):
    from run import main
    main(args)


def plots(_):
    from vsi import plots as p
    p.main()


def check(_):
    from vsi.check import check as run_check
    run_check("docs/REQUIREMENTS.md")


def context(_):
    from vsi.context import write_context
    print(write_context(ROOT))


COMMANDS = {f.__name__: f for f in (setup, data, test, run, plots, check, context)}

if __name__ == "__main__":
    if len(sys.argv) < 2 or sys.argv[1] not in COMMANDS:
        print(__doc__)
        sys.exit(1)
    COMMANDS[sys.argv[1]](sys.argv[2:])
