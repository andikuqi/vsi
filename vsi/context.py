"""Bundle the project into ONE markdown file for chat-only AIs (ChatGPT, Copilot 365, Gemini web)."""

from __future__ import annotations

from pathlib import Path

PARTS = ["AGENTS.md", "docs/PROBLEM.md", "docs/REQUIREMENTS.md", "docs/DECISIONS.md", "results/metrics.csv"]
CODE_GLOBS = ["src/**/*.py"]
MAX_FILE_CHARS = 15_000


def write_context(root: str | Path = ".", out: str = "CONTEXT.md", include_code: bool = True) -> Path:
    root = Path(root)
    chunks = ["# Project context (generated by VSI — upload this file to your AI chat)\n"]
    for rel in PARTS:
        p = root / rel
        if p.exists():
            chunks.append(f"\n---\n## {rel}\n\n{p.read_text(encoding='utf-8')[:MAX_FILE_CHARS]}\n")
    if include_code:
        for pattern in CODE_GLOBS:
            for p in sorted(root.glob(pattern)):
                if "__pycache__" in p.parts:
                    continue
                code = p.read_text(encoding="utf-8")[:MAX_FILE_CHARS]
                chunks.append(f"\n---\n## {p.relative_to(root).as_posix()}\n\n```python\n{code}\n```\n")
    path = root / out
    path.write_text("".join(chunks), encoding="utf-8")
    return path
